// Builds src/KorTrainer.Infrastructure/Seed/audio-lingualibre.json — native-speaker recordings of
// Korean words from Lingua Libre (hosted on Wikimedia Commons). Run from the repository root:
//
//   dotnet run tools/audio/BuildAudioManifest.cs
//
// Only openly licensed files are kept (CC0, CC BY, CC BY-SA), one recording per word, preferring the
// speakers with the most recordings so voices stay consistent. The app downloads the audio itself on
// demand and caches it; this manifest only stores where each file is and how to credit it.

using System.Net;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using System.Text.Unicode;

const string Api = "https://commons.wikimedia.org/w/api.php";
const string Category = "Category:Lingua_Libre_pronunciation-kor";
const string UserAgent = "KorTrainer/1.0 (+https://lingualibre.org; audio manifest builder) dotnet-HttpClient/10";
var politeDelay = TimeSpan.FromMilliseconds(500);
var titlePattern = new Regex(@"^File:LL-Q9176 \(kor\)-(?<speaker>.+?)-(?<word>.+)\.(wav|ogg|flac|mp3)$");
string[] allowedLicenses = ["CC0", "CC BY", "CC BY-SA", "Public domain"];

using var http = new HttpClient();
http.DefaultRequestHeaders.UserAgent.ParseAdd(UserAgent);

var recordings = new List<Recording>();
var query = new Dictionary<string, string>
{
    ["action"] = "query",
    ["generator"] = "categorymembers",
    ["gcmtitle"] = Category,
    ["gcmtype"] = "file",
    ["gcmlimit"] = "50",
    ["prop"] = "videoinfo",
    ["viprop"] = "url|derivatives|extmetadata",
    ["format"] = "json",
    ["maxlag"] = "5",
};

while (true)
{
    string url = Api + "?" + string.Join('&', query.Select(kv => $"{kv.Key}={Uri.EscapeDataString(kv.Value)}"));
    var page = JsonNode.Parse(await http.GetStringAsync(url))!;
    foreach (var (_, item) in page["query"]?["pages"]?.AsObject() ?? [])
    {
        if (ToRecording(item!) is { } recording)
        {
            recordings.Add(recording);
        }
    }

    if (page["continue"] is not JsonObject next)
    {
        break;
    }

    foreach (var (key, value) in next)
    {
        query[key] = value!.GetValue<string>();
    }

    await Task.Delay(politeDelay);
}

var speakerRank = recordings.GroupBy(r => r.Speaker).ToDictionary(g => g.Key, g => g.Count());
var chosen = recordings
    .GroupBy(r => r.Word)
    .Select(g => g.OrderByDescending(r => speakerRank[r.Speaker]).ThenBy(r => r.File, StringComparer.Ordinal).First())
    .OrderBy(r => r.Word, StringComparer.Ordinal)
    .ToList();

var manifest = new JsonObject
{
    ["source"] = "Lingua Libre (https://lingualibre.org) via Wikimedia Commons, category " + Category,
    ["note"] = "Generated by tools/audio/BuildAudioManifest.cs. Each recording keeps its own license and author; see the credits page. Do not edit by hand.",
    ["recordings"] = new JsonArray(chosen.Select(r => (JsonNode)new JsonObject
    {
        ["word"] = r.Word,
        ["speaker"] = r.Speaker,
        ["license"] = r.License,
        ["licenseUrl"] = r.LicenseUrl,
        ["page"] = r.Page,
        ["url"] = r.Url,
    }).ToArray()),
};

string output = Path.Combine(Directory.GetCurrentDirectory(), "src", "KorTrainer.Infrastructure", "Seed", "audio-lingualibre.json");
var options = new JsonSerializerOptions { WriteIndented = true, Encoder = JavaScriptEncoder.Create(UnicodeRanges.All) };
File.WriteAllText(output, manifest.ToJsonString(options) + Environment.NewLine);
Console.WriteLine($"{recordings.Count} openly licensed files, {chosen.Count} words → {output}");
foreach (var license in chosen.GroupBy(r => r.License).OrderByDescending(g => g.Count()))
{
    Console.WriteLine($"  {license.Key}: {license.Count()}");
}

Recording? ToRecording(JsonNode item)
{
    string title = item["title"]!.GetValue<string>();
    var match = titlePattern.Match(title);
    var info = item["videoinfo"]?[0];
    if (!match.Success || info is null)
    {
        return null;
    }

    string word = match.Groups["word"].Value.Trim();
    if (word.Length == 0 || !word.All(c => c is >= '가' and <= '힣' or ' '))
    {
        return null; // hanja, Latin or digits: not useful for the Korean deck
    }

    var meta = info["extmetadata"];
    string license = meta?["LicenseShortName"]?["value"]?.GetValue<string>() ?? string.Empty;
    if (!allowedLicenses.Any(a => license.StartsWith(a, StringComparison.OrdinalIgnoreCase)))
    {
        return null;
    }

    string licenseUrl = meta?["LicenseUrl"]?["value"]?.GetValue<string>() ?? string.Empty;
    string audioUrl = info["derivatives"]?.AsArray()
        .FirstOrDefault(d => d?["transcodekey"]?.GetValue<string>() == "mp3")?["src"]?.GetValue<string>()
        ?? info["url"]!.GetValue<string>();

    return new Recording(
        word,
        WebUtility.HtmlDecode(match.Groups["speaker"].Value),
        license,
        licenseUrl.StartsWith("//", StringComparison.Ordinal) ? "https:" + licenseUrl : licenseUrl,
        title,
        "https://commons.wikimedia.org/wiki/" + Uri.EscapeDataString(title.Replace(' ', '_')),
        audioUrl.Split('?')[0]);
}

internal sealed record Recording(string Word, string Speaker, string License, string LicenseUrl, string File, string Page, string Url);
