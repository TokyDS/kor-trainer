#:property PublishAot=false

// Builds src/KorTrainer.Infrastructure/Seed/words-nikl.json from the NIKL learner vocabulary list
// and its Russian translations. Run from the repository root:
//
//   dotnet run tools/deck/BuildNiklDeck.cs
//
// Inputs (tools/deck):
//   nikl-learner-vocabulary.tsv  key, word, pos, hanja, grade (A/B/C), frequency rank — exported from
//                                "한국어 학습용 어휘 목록" (National Institute of Korean Language, 2003, KOGL Type 1)
//   nikl.ru.tsv                  "key|pos", Russian translation, irregularity code (b/d/reu/s/h or empty)
// Words already present in the curated deck (Seed/words.json) are skipped; rows without a translation
// are skipped too, so grade C can be added later just by translating it.

using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.Unicode;

const int BandSize = 100;
const int LevelTwoBWords = 1000;

string root = Directory.GetCurrentDirectory();
string toolsDir = Path.Combine(root, "tools", "deck");
string seedDir = Path.Combine(root, "src", "KorTrainer.Infrastructure", "Seed");

var curated = JsonNode.Parse(File.ReadAllText(Path.Combine(seedDir, "words.json")))!["sections"]!.AsArray()
    .SelectMany(section => section!["words"]!.AsArray())
    .Select(word => word![0]!.GetValue<string>())
    .ToHashSet();

var translations = File.ReadLines(Path.Combine(toolsDir, "nikl.ru.tsv"))
    .Where(line => line.Length > 0)
    .Select(line => line.Split('\t'))
    .ToDictionary(parts => parts[0], parts => (Russian: parts[1].Trim(), Irregularity: parts.Length > 2 ? parts[2].Trim() : string.Empty));

var rows = File.ReadLines(Path.Combine(toolsDir, "nikl-learner-vocabulary.tsv"))
    .Where(line => line.Length > 0)
    .Select(line => line.Split('\t'))
    // "도쿄(동경)": keep the modern reading, drop the alternative in parentheses.
    .Select(p => new NiklRow(p[0], p[1].Split('(')[0].Trim(), p[2], p[3], p[4], int.Parse(p[5])))
    .Where(r => !curated.Contains(r.Word) && translations.ContainsKey(r.TranslationKey))
    .OrderBy(r => "ABC".IndexOf(r.Grade))
    .ThenBy(r => r.Rank)
    // NIKL lists some words under two parts of speech with the same meaning (만: numeral and
    // determiner); one flashcard is enough.
    .DistinctBy(r => (r.Word, FirstSense(translations[r.TranslationKey].Russian)))
    .ToList();

static string FirstSense(string russian)
{
    int cut = russian.IndexOfAny([',', ';', '(']);
    return (cut > 0 ? russian[..cut] : russian).Trim().ToLowerInvariant();
}

var sections = new JsonArray();
foreach (var grade in rows.GroupBy(r => r.Grade))
{
    var words = grade.ToList();
    for (int start = 0; start < words.Count; start += BandSize)
    {
        var band = words.Skip(start).Take(BandSize).ToList();
        string stage = (grade.Key, start) switch
        {
            ("A", _) => "Level1",
            ("B", < LevelTwoBWords) => "Level2",
            _ => "TopikPrep",
        };

        var entries = new JsonArray();
        foreach (var row in band)
        {
            var (russian, irregularity) = translations[row.TranslationKey];
            var entry = new JsonArray(row.Word, russian, row.PartOfSpeech);
            if (irregularity.Length > 0)
            {
                entry.Add(irregularity);
            }

            entries.Add(entry);
        }

        sections.Add(new JsonObject
        {
            ["stage"] = stage,
            ["topic"] = $"Частотные {grade.Key} · {start + 1}–{start + band.Count}",
            ["words"] = entries,
        });
    }
}

var deck = new JsonObject
{
    ["version"] = 1,
    ["note"] = "Generated by tools/deck/BuildNiklDeck.cs from 한국어 학습용 어휘 목록 (National Institute of Korean Language, 2003; KOGL Type 1, attribution required). Russian translations were machine-generated and should be reviewed. Do not edit by hand.",
    ["sections"] = sections,
};

var options = new JsonSerializerOptions
{
    WriteIndented = true,
    Encoder = JavaScriptEncoder.Create(UnicodeRanges.All),
};
string output = Path.Combine(seedDir, "words-nikl.json");
File.WriteAllText(output, deck.ToJsonString(options) + Environment.NewLine);
Console.WriteLine($"{rows.Count} words in {sections.Count} sections → {output}");
foreach (var group in rows.GroupBy(r => r.Grade))
{
    Console.WriteLine($"  grade {group.Key}: {group.Count()}");
}

internal sealed record NiklRow(string Key, string Word, string Pos, string Hanja, string Grade, int Rank)
{
    public string TranslationKey => $"{Key}|{Pos}";

    /// <summary>Maps NIKL part-of-speech codes to the deck's PartOfSpeech names.</summary>
    public string PartOfSpeech => Pos switch
    {
        "명" or "의" or "고" => "noun",
        "동" => "verb",
        "형" => "adjective",
        "부" => "adverb",
        "대" => "pronoun",
        "수" => "numeral",
        "관" => "determiner",
        _ => "phrase", // 보 (auxiliaries), 감 (interjections), 불 (contractions) are learned as phrases
    };
}
