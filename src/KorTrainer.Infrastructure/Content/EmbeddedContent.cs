using System.Text.Json;
using KorTrainer.Application.Common;
using KorTrainer.Domain.Plan;
using KorTrainer.Domain.Vocabulary;

namespace KorTrainer.Infrastructure.Content;

/// <summary>Reads bundled reference files embedded in this assembly.</summary>
internal static class EmbeddedResource
{
    public static readonly JsonSerializerOptions Json = new() { PropertyNameCaseInsensitive = true };

    public static Stream Open(string fileName) =>
        typeof(EmbeddedResource).Assembly.GetManifestResourceStream($"KorTrainer.Infrastructure.Seed.{fileName}")
        ?? throw new InvalidOperationException($"Embedded resource '{fileName}' was not found.");

    public static T ReadJson<T>(string fileName)
    {
        using var stream = Open(fileName);
        return JsonSerializer.Deserialize<T>(stream, Json) ?? throw new InvalidDataException($"'{fileName}' is empty.");
    }
}

/// <summary>Seed/hanja-glosses.tsv: character, 훈, Russian gloss.</summary>
public sealed class EmbeddedHanjaGlossary : IHanjaGlossary
{
    private readonly Lazy<IReadOnlyDictionary<char, HanjaGloss>> _glosses = new(Load);

    public IReadOnlyDictionary<char, HanjaGloss> Glosses => _glosses.Value;

    private static IReadOnlyDictionary<char, HanjaGloss> Load()
    {
        using var reader = new StreamReader(EmbeddedResource.Open("hanja-glosses.tsv"));
        var glosses = new Dictionary<char, HanjaGloss>();
        while (reader.ReadLine() is { } line)
        {
            var parts = line.Split('\t');
            if (parts.Length == 3 && parts[0].Length == 1)
            {
                glosses[parts[0][0]] = new HanjaGloss(parts[1].Trim(), parts[2].Trim());
            }
        }

        return glosses;
    }
}

/// <summary>Seed/sentences-tatoeba.json, generated by tools/sentences/BuildSentences.cs.</summary>
public sealed class EmbeddedGrammarSentenceLibrary : IGrammarSentenceLibrary
{
    private readonly Lazy<IReadOnlyList<GrammarSentence>> _sentences = new(() =>
        EmbeddedResource.ReadJson<GrammarSentenceFile>("grammar-sentences.json").Sentences
            .Select(s => new GrammarSentence(s.Id, s.Topic, Enum.Parse<PlanStage>(s.Stage), s.Ko, s.Ru))
            .ToList());

    public IReadOnlyList<GrammarSentence> Sentences => _sentences.Value;

    private sealed record GrammarSentenceFile(int Version, IReadOnlyList<GrammarSentenceRow> Sentences);

    private sealed record GrammarSentenceRow(int Id, string Topic, string Stage, string Ko, string Ru);
}

public sealed class EmbeddedSentenceLibrary : ISentenceLibrary
{
    private readonly Lazy<(IReadOnlyList<ExampleSentence> All, ILookup<string, ExampleSentence> ByWord)> _data = new(Load);

    public IReadOnlyList<ExampleSentence> Sentences => _data.Value.All;

    public IReadOnlyList<ExampleSentence> ForWord(string deckKey) => [.. _data.Value.ByWord[deckKey]];

    private static (IReadOnlyList<ExampleSentence>, ILookup<string, ExampleSentence>) Load()
    {
        var file = EmbeddedResource.ReadJson<SentenceFile>("sentences-tatoeba.json");
        var all = file.Sentences
            .Select(s => new ExampleSentence(s.Id, s.Ko, s.Ru, s.Author, s.Machine, s.Words))
            .ToList();
        var byWord = all
            .SelectMany(s => s.WordKeys.Distinct().Select(k => (Key: k, Sentence: s)))
            .OrderBy(x => x.Sentence.MachineTranslated)
            .ThenBy(x => x.Sentence.Korean.Length)
            .ToLookup(x => x.Key, x => x.Sentence, StringComparer.Ordinal);
        return (all, byWord);
    }

    private sealed record SentenceFile(int Version, IReadOnlyList<SentenceRow> Sentences);

    private sealed record SentenceRow(int Id, string Ko, string Ru, string Author, bool Machine, IReadOnlyList<string> Words);
}
