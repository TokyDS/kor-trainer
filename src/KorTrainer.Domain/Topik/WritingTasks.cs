    public static WritingTask? Find(int number) => All.FirstOrDefault(t => t.Number == number);

    /// <summary>Characters as counted on 원고지 manuscript paper: spaces count, line breaks do not.</summary>
    public static int CountCharacters(string text)
    {
        ArgumentNullException.ThrowIfNull(text);
        return text.Count(c => c is not ('\n' or '\r'));
    }
