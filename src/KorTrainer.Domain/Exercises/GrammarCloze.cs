using System.Text.RegularExpressions;
using KorTrainer.Domain.Grammar;
using KorTrainer.Domain.Hangul;

namespace KorTrainer.Domain.Exercises;

/// <summary>An example sentence that can carry a grammar gap.</summary>
public sealed record ClozeSentence(int Id, string Korean, string Russian, bool MachineTranslated);

/// <summary>A deck word used in a topic's form inside a sentence: <c>Korean[Start..(Start + Length)] == Form</c>.</summary>
public sealed record ClozeMatch(
    ClozeSentence Sentence,
    int Start,
    int Length,
    GrammarTopic Topic,
    string Form,
    GrammarVerb? Verb = null,
    GrammarNoun? Noun = null);

/// <summary>
/// Finds conjugated deck verbs and nouns with particles in real sentences, so a drill can blank them out.
/// Forms are generated by <see cref="Conjugator"/> and <see cref="Particles"/>, then looked up word by word,
/// longest first (먹고 싶어요 wins over 먹고).
/// </summary>
public static partial class GrammarClozeFinder
{
    private const int MaxFormWords = 3;

    // One-syllable nouns + particle collide with other words too often (가 + 는 = 가는).
    private const int MinParticleNounLength = 2;

    // Auxiliaries: blanking 않고 in 지불하지 않고 tests the wrong thing.
    private static readonly HashSet<string> Auxiliaries = ["않다"];

    // At the start of a sentence these are conjunctions (하지만, 그래서), not a verb with an ending.
    private static readonly HashSet<Ending> Connectives =
        [Ending.And, Ending.SoThat, Ending.Because, Ending.But, Ending.If, Ending.BecauseGi];

    private sealed record Candidate(GrammarTopic Topic, string Word, GrammarVerb? Verb, GrammarNoun? Noun);

    public static IReadOnlyList<ClozeMatch> Find(
        IEnumerable<ClozeSentence> sentences,
        IEnumerable<GrammarTopic> topics,
        IReadOnlyList<GrammarNoun> nouns,
        IReadOnlyList<GrammarVerb> verbs)
    {
        ArgumentNullException.ThrowIfNull(sentences);
        var forms = FormsOf(topics.ToList(), nouns, verbs);
        return sentences.SelectMany(s => Scan(s, forms)).ToList();
    }

    private static Dictionary<string, Candidate> FormsOf(
        IReadOnlyList<GrammarTopic> topics, IReadOnlyList<GrammarNoun> nouns, IReadOnlyList<GrammarVerb> verbs)
    {
        var all = new Dictionary<string, List<Candidate>>(StringComparer.Ordinal);
        void Add(string form, Candidate candidate)
        {
            if (!all.TryGetValue(form, out var list))
            {
                all[form] = list = [];
            }

            list.Add(candidate);
        }

        var usableVerbs = verbs
            .Where(v => v.Korean.Length >= 2 && v.Korean[^1] == '다' && v.Korean.All(Syllable.IsSyllable) && !Auxiliaries.Contains(v.Korean))
            .ToList();
        var usableNouns = nouns.Where(n => n.Korean.Length >= MinParticleNounLength && n.Korean.All(Syllable.IsSyllable)).ToList();
        foreach (var topic in topics)
        {
            if (topic.Ending is { } ending)
            {
                foreach (var verb in usableVerbs)
                {
                    Add(Conjugator.Conjugate(verb.Korean, ending, verb.Irregularity).Form, new Candidate(topic, verb.Korean, verb, null));
                }
            }
            else if (topic.Particle is { } kind)
            {
                foreach (var noun in usableNouns)
                {
                    Add(Particles.Attach(noun.Korean, kind).Form, new Candidate(topic, noun.Korean, null, noun));
                }
            }
        }

        // A form two different words share (사요: 사다 or 살다?) cannot be blanked unambiguously.
        return all
            .Where(e => e.Value.Select(c => c.Word).Distinct().Count() == 1)
            .ToDictionary(e => e.Key, e => e.Value[0], StringComparer.Ordinal);
    }

    private static IEnumerable<ClozeMatch> Scan(ClozeSentence sentence, Dictionary<string, Candidate> forms)
    {
        var words = WordPattern().Matches(sentence.Korean);
        int i = 0;
        while (i < words.Count)
        {
            var match = LongestAt(sentence, words, i, forms);
            if (match is null)
            {
                i++;
                continue;
            }

            yield return match.Value.Match;
            i += match.Value.Words;
        }
    }

    private static (ClozeMatch Match, int Words)? LongestAt(
        ClozeSentence sentence, MatchCollection words, int first, Dictionary<string, Candidate> forms)
    {
        for (int count = Math.Min(MaxFormWords, words.Count - first); count >= 1; count--)
        {
            int start = words[first].Index;
            var lastWord = words[first + count - 1];
            int end = lastWord.Index + lastWord.Length;

            // Punctuation may only wrap the whole span: "가요?" and «책이에요» match, "가요, 먹어요" does not.
            while (start < end && !Syllable.IsSyllable(sentence.Korean[start]))
            {
                start++;
            }

            while (end > start && !Syllable.IsSyllable(sentence.Korean[end - 1]))
            {
                end--;
            }

            string text = WhitespacePattern().Replace(sentence.Korean[start..end], " ");
            if (forms.TryGetValue(text, out var candidate)
                && text.All(c => c == ' ' || Syllable.IsSyllable(c))
                && !(start == 0 && candidate.Topic.Ending is { } ending && Connectives.Contains(ending)))
            {
                return (new ClozeMatch(sentence, start, end - start, candidate.Topic, text, candidate.Verb, candidate.Noun), count);
            }
        }

        return null;
    }

    [GeneratedRegex(@"\S+")]
    private static partial Regex WordPattern();

    [GeneratedRegex(@"\s+")]
    private static partial Regex WhitespacePattern();
}
